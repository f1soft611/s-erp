-- 대상 DB: s-erp_central (PostgreSQL)
-- 목적: 창고(warehouse) 실무 운영용 테이블 재생성
--       2026-09-09에 생성한 테스트용 tb_warehouse(warehouse_nm, use_at 등)를 대체한다.

CREATE TABLE public.tb_warehouse (
    warehouse_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id             BIGINT       NOT NULL,
    warehouse_code        VARCHAR(10)  NOT NULL,
    warehouse_name        VARCHAR(100) NOT NULL,
    warehouse_type        VARCHAR(50),
    delete_lock_at        CHAR(1)      NOT NULL DEFAULT 'N',
    disuse_at             CHAR(1)      NOT NULL DEFAULT 'N',
    stock_qty_disp_at     CHAR(1)      NOT NULL DEFAULT 'Y',
    stock_io_at           CHAR(1)      NOT NULL DEFAULT 'Y',
    safety_stock_alert_at CHAR(1)      NOT NULL DEFAULT 'N',
    stock_default_at      CHAR(1)      NOT NULL DEFAULT 'N',
    plant_id              BIGINT,
    customer_id           BIGINT,
    manager_user_id       BIGINT,
    department_id         BIGINT,
    tel_no                VARCHAR(20),
    fax_no                VARCHAR(20),
    address               VARCHAR(300),
    remark                VARCHAR(1000),
    created_by            BIGINT,
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by            BIGINT,
    updated_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_tb_warehouse PRIMARY KEY (warehouse_id),
    CONSTRAINT uq_tb_warehouse_tenant_code UNIQUE (tenant_id, warehouse_code),
    CONSTRAINT fk_tb_warehouse_tenant
        FOREIGN KEY (tenant_id) REFERENCES public.tb_tenant (tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_tb_warehouse_customer
        FOREIGN KEY (customer_id, tenant_id) REFERENCES public.tb_customer_info (customer_id, tenant_id),
    CONSTRAINT fk_tb_warehouse_manager_user
        FOREIGN KEY (manager_user_id) REFERENCES public.tb_user (user_id),
    CONSTRAINT fk_tb_warehouse_department
        FOREIGN KEY (department_id) REFERENCES public.tb_department (department_id),
    CONSTRAINT ck_tb_warehouse_yn CHECK (
        delete_lock_at        IN ('Y','N') AND
        disuse_at             IN ('Y','N') AND
        stock_qty_disp_at     IN ('Y','N') AND
        stock_io_at           IN ('Y','N') AND
        safety_stock_alert_at IN ('Y','N') AND
        stock_default_at      IN ('Y','N')
    )
);

CREATE INDEX ix_tb_warehouse_tenant_id ON public.tb_warehouse (tenant_id);

COMMENT ON TABLE  public.tb_warehouse                       IS '창고';
COMMENT ON COLUMN public.tb_warehouse.warehouse_id          IS '창고ID';
COMMENT ON COLUMN public.tb_warehouse.tenant_id             IS '테넌트ID';
COMMENT ON COLUMN public.tb_warehouse.warehouse_code        IS '창고코드';
COMMENT ON COLUMN public.tb_warehouse.warehouse_name        IS '창고명';
COMMENT ON COLUMN public.tb_warehouse.warehouse_type        IS '창고구분(공통코드 WAREHOUSE_TYPE)';
COMMENT ON COLUMN public.tb_warehouse.delete_lock_at        IS '삭제불가여부(Y/N)';
COMMENT ON COLUMN public.tb_warehouse.disuse_at             IS '불용창고여부(Y=불용, N=사용)';
COMMENT ON COLUMN public.tb_warehouse.stock_qty_disp_at     IS '현재고표시여부(Y/N)';
COMMENT ON COLUMN public.tb_warehouse.stock_io_at           IS '수불처리여부(Y/N)';
COMMENT ON COLUMN public.tb_warehouse.safety_stock_alert_at IS '안전재고미달알림여부(Y/N)';
COMMENT ON COLUMN public.tb_warehouse.stock_default_at      IS '재고현황기본조회포함여부(Y/N)';
COMMENT ON COLUMN public.tb_warehouse.plant_id              IS '사업장ID';
COMMENT ON COLUMN public.tb_warehouse.customer_id           IS '거래처ID';
COMMENT ON COLUMN public.tb_warehouse.manager_user_id       IS '담당자 사용자ID';
COMMENT ON COLUMN public.tb_warehouse.department_id         IS '담당부서ID';
COMMENT ON COLUMN public.tb_warehouse.tel_no                IS '전화번호';
COMMENT ON COLUMN public.tb_warehouse.fax_no                IS '팩스번호';
COMMENT ON COLUMN public.tb_warehouse.address               IS '주소';
COMMENT ON COLUMN public.tb_warehouse.remark                IS '비고';
COMMENT ON COLUMN public.tb_warehouse.created_by            IS '등록자';
COMMENT ON COLUMN public.tb_warehouse.created_at            IS '등록일시';
