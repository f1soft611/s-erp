-- 20261105_004 시스템 정책 저장소 생성
-- 대상: public.tb_system_policy, public.tb_system_policy_history (신규), 기존 tb_tenant 는 읽기 전용으로 참조
-- 기본 정책 DELIVERY_PLAN_MODE / OVER_DELIVERY_POLICY 는 현재 tb_tenant 적용값을 그대로 복제한다.
-- 실제 적용값의 원천은 계속 tb_tenant 컬럼이며 이 스크립트는 tb_tenant 를 수정하지 않는다.
-- 운영 DB 적용은 별도 승인 절차를 따른다.
BEGIN;

DO $system_policy_precheck$
BEGIN
    IF to_regclass('public.tb_system_policy') IS NOT NULL
        OR to_regclass('public.tb_system_policy_history') IS NOT NULL THEN
        RAISE EXCEPTION 'System policy tables already exist. Review existing schema before applying 20261105_004.';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.tb_tenant t
        WHERE t.delivery_plan_mode NOT IN ('AUTO', 'MANUAL')
           OR t.over_delivery_policy NOT IN ('BLOCK', 'WARN')
    ) THEN
        RAISE EXCEPTION 'Tenant delivery policy columns contain unsupported values. Review before seeding.';
    END IF;
END;
$system_policy_precheck$;

CREATE TABLE public.tb_system_policy (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES public.tb_tenant (tenant_id),
    policy_code VARCHAR(80) NOT NULL,
    policy_nm VARCHAR(100) NOT NULL,
    category_nm VARCHAR(80) NOT NULL,
    policy_dc VARCHAR(1000) NOT NULL DEFAULT '',
    value_type VARCHAR(20) NOT NULL,
    value_json JSONB NOT NULL,
    options_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    min_value NUMERIC NULL,
    max_value NUMERIC NULL,
    unit_nm VARCHAR(30) NOT NULL DEFAULT '',
    version INTEGER NOT NULL DEFAULT 1,
    system_policy_at CHAR(1) NOT NULL DEFAULT 'N',
    created_by BIGINT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_system_policy_tenant_code UNIQUE (tenant_id, policy_code),
    CONSTRAINT ck_system_policy_code CHECK (policy_code ~ '^[A-Z0-9_]{2,80}$'),
    CONSTRAINT ck_system_policy_required_text CHECK (btrim(policy_nm) <> '' AND btrim(category_nm) <> ''),
    CONSTRAINT ck_system_policy_value_type CHECK (value_type IN ('BOOLEAN', 'NUMBER', 'SELECT', 'TEXT', 'DATE', 'USER_LIST')),
    CONSTRAINT ck_system_policy_options_array CHECK (jsonb_typeof(options_json) = 'array'),
    CONSTRAINT ck_system_policy_value_shape CHECK (
        (value_type = 'BOOLEAN' AND jsonb_typeof(value_json) = 'boolean')
        OR (value_type = 'NUMBER' AND jsonb_typeof(value_json) = 'number')
        OR (value_type IN ('SELECT', 'TEXT', 'DATE') AND jsonb_typeof(value_json) = 'string')
        OR (value_type = 'USER_LIST' AND jsonb_typeof(value_json) = 'array')
    ),
    CONSTRAINT ck_system_policy_range CHECK (min_value IS NULL OR max_value IS NULL OR min_value <= max_value),
    CONSTRAINT ck_system_policy_version CHECK (version >= 1),
    CONSTRAINT ck_system_policy_system_at CHECK (system_policy_at IN ('Y', 'N')),
    CONSTRAINT ck_system_policy_builtin CHECK (
        (policy_code IN ('DELIVERY_PLAN_MODE', 'OVER_DELIVERY_POLICY')) = (system_policy_at = 'Y')
    )
);

COMMENT ON TABLE public.tb_system_policy IS '테넌트별 시스템 정책 정의와 값';
COMMENT ON COLUMN public.tb_system_policy.value_json IS '정책 값 raw JSON. 기본 정책은 tb_tenant 컬럼이 실제 원천이며 이 값은 복제본';
COMMENT ON COLUMN public.tb_system_policy.options_json IS 'SELECT 선택지 [{value,label}] 배열';
COMMENT ON COLUMN public.tb_system_policy.version IS '낙관적 잠금 버전';
COMMENT ON COLUMN public.tb_system_policy.system_policy_at IS '시스템 기본 정책 여부(Y: 삭제/타입/선택지 변경 불가)';

-- 삭제 이력 보존을 위해 정책 FK/CASCADE 를 두지 않는다.
CREATE TABLE public.tb_system_policy_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES public.tb_tenant (tenant_id),
    policy_id BIGINT NOT NULL,
    policy_code VARCHAR(80) NOT NULL,
    action_cd VARCHAR(10) NOT NULL,
    before_value JSONB NULL,
    after_value JSONB NULL,
    before_snapshot JSONB NULL,
    after_snapshot JSONB NULL,
    changed_by BIGINT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_system_policy_history_action CHECK (action_cd IN ('CREATE', 'UPDATE', 'DELETE')),
    CONSTRAINT ck_system_policy_history_snapshot CHECK (
        (action_cd = 'CREATE' AND before_snapshot IS NULL AND after_snapshot IS NOT NULL)
        OR (action_cd = 'UPDATE' AND before_snapshot IS NOT NULL AND after_snapshot IS NOT NULL)
        OR (action_cd = 'DELETE' AND before_snapshot IS NOT NULL AND after_snapshot IS NULL)
    )
);

CREATE INDEX ix_system_policy_history_policy
    ON public.tb_system_policy_history (tenant_id, policy_id, changed_at DESC, history_id DESC);

COMMENT ON TABLE public.tb_system_policy_history IS '시스템 정책 생성/수정/삭제 전후 이력';

INSERT INTO public.tb_system_policy (
    tenant_id, policy_code, policy_nm, category_nm, policy_dc, value_type,
    value_json, options_json, unit_nm, version, system_policy_at
)
SELECT t.tenant_id, 'DELIVERY_PLAN_MODE', '납품계획 운영모드', '영업관리',
       '납품계획을 수주 기준으로 자동 생성할지 수동 등록할지 결정합니다.', 'SELECT',
       to_jsonb(t.delivery_plan_mode),
       '[{"value":"AUTO","label":"자동 생성"},{"value":"MANUAL","label":"수동 등록"}]'::jsonb,
       '', 1, 'Y'
FROM public.tb_tenant t
UNION ALL
SELECT t.tenant_id, 'OVER_DELIVERY_POLICY', '초과납품 정책', '영업관리',
       '수주 잔량을 초과하는 납품을 차단할지 경고 후 허용할지 결정합니다.', 'SELECT',
       to_jsonb(t.over_delivery_policy),
       '[{"value":"BLOCK","label":"초과 차단"},{"value":"WARN","label":"경고 후 허용"}]'::jsonb,
       '', 1, 'Y'
FROM public.tb_tenant t
ON CONFLICT (tenant_id, policy_code) DO NOTHING;

COMMIT;