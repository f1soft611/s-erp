BEGIN;
CREATE TABLE tb_process_group (
    group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tb_tenant(tenant_id),
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    inactive BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (tenant_id, group_id),
    CHECK (length(trim(name)) > 0)
);
CREATE TABLE tb_process (
    process_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tb_tenant(tenant_id),
    group_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    image TEXT,
    inactive BOOLEAN NOT NULL DEFAULT FALSE,
    production_outsource BOOLEAN NOT NULL DEFAULT FALSE,
    purchase_outsource BOOLEAN NOT NULL DEFAULT FALSE,
    inspection BOOLEAN NOT NULL DEFAULT FALSE,
    packing BOOLEAN NOT NULL DEFAULT FALSE,
    stock_management BOOLEAN NOT NULL DEFAULT FALSE,
    previous_stock_out BOOLEAN NOT NULL DEFAULT FALSE,
    final_process BOOLEAN NOT NULL DEFAULT FALSE,
    planned_equipment BOOLEAN NOT NULL DEFAULT FALSE,
    actual_equipment_required BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (tenant_id, group_id) REFERENCES tb_process_group (tenant_id, group_id),
    CHECK (length(trim(name)) > 0)
);
CREATE INDEX idx_process_group ON tb_process (tenant_id, group_id);
COMMIT;
