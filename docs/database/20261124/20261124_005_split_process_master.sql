-- 공정을 작업장 종속에서 분리해 공정 마스터로 독립시키고 작업장-공정 매핑 테이블을 만든다.
-- 병합 기준: 테넌트 + 이름 + inactive + 9개 공정 속성 플래그. 마스터는 가장 작은 process_id.
-- 이미 매핑 테이블이 있거나 group_id 컬럼이 없으면 중단한다.
BEGIN;

LOCK TABLE public.tb_process_group, public.tb_process IN ACCESS EXCLUSIVE MODE;

DO $guard$
BEGIN
    IF to_regclass('public.tb_process_group_process') IS NOT NULL THEN
        RAISE EXCEPTION 'tb_process_group_process already exists; review before applying.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = 'tb_process' AND column_name = 'group_id') THEN
        RAISE EXCEPTION 'tb_process.group_id does not exist; schema is not in the expected state.';
    END IF;
END
$guard$;

ALTER TABLE public.tb_process ADD CONSTRAINT uq_process_tenant_process UNIQUE (tenant_id, process_id);

CREATE TABLE public.tb_process_group_process (
    map_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    process_id BIGINT NOT NULL,
    sort_seq INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_process_group_process UNIQUE (tenant_id, group_id, process_id),
    CONSTRAINT fk_process_group_process_group FOREIGN KEY (tenant_id, group_id)
        REFERENCES public.tb_process_group (tenant_id, group_id),
    CONSTRAINT fk_process_group_process_process FOREIGN KEY (tenant_id, process_id)
        REFERENCES public.tb_process (tenant_id, process_id)
);
CREATE INDEX idx_process_group_process_process ON public.tb_process_group_process (tenant_id, process_id);

COMMENT ON TABLE public.tb_process_group_process IS '작업장(공정그룹)-공정 연결. 공정 마스터를 여러 작업장에서 재사용한다';
COMMENT ON COLUMN public.tb_process_group_process.group_id IS '작업장(tb_process_group) ID';
COMMENT ON COLUMN public.tb_process_group_process.process_id IS '공정 마스터(tb_process) ID';
COMMENT ON COLUMN public.tb_process_group_process.sort_seq IS '작업장 안 표시 순서';
COMMENT ON TABLE public.tb_process IS '테넌트별 공정 마스터. 작업장 연결은 tb_process_group_process';
COMMENT ON TABLE public.tb_process_group IS '테넌트별 작업장(구 공정그룹)';

CREATE TEMP TABLE tmp_process_master ON COMMIT DROP AS
SELECT process_id,
       MIN(process_id) OVER (PARTITION BY tenant_id, name, inactive, production_outsource,
           purchase_outsource, inspection, packing, stock_management, previous_stock_out,
           final_process, planned_equipment, actual_equipment_required) AS master_id
FROM public.tb_process;

INSERT INTO public.tb_process_group_process (tenant_id, group_id, process_id, sort_seq)
SELECT p.tenant_id, p.group_id, m.master_id, 0
FROM public.tb_process p JOIN tmp_process_master m ON m.process_id = p.process_id
GROUP BY p.tenant_id, p.group_id, m.master_id
ORDER BY p.tenant_id, p.group_id, MIN(p.process_id);

DELETE FROM public.tb_process p USING tmp_process_master m
WHERE m.process_id = p.process_id AND m.master_id <> p.process_id;

ALTER TABLE public.tb_process DROP CONSTRAINT tb_process_tenant_id_group_id_fkey;
DROP INDEX public.idx_process_group;
ALTER TABLE public.tb_process DROP COLUMN group_id;

COMMIT;
